#!/usr/bin/env python3
"""Tool 2 — send a short demo summary email (educational).

Default is --dry-run (no network send). Pass --send to deliver.
Recipient must be on the allow-list (GMAIL_TO / DEMO_OWNER_EMAIL / GMAIL_ALLOWED_TO).

Examples (repo root, venv on):

  python control/scripts/send_demo_email.py
  python control/scripts/send_demo_email.py --send
  python control/scripts/send_demo_email.py --to you@example.com --subject "S1 draft"
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from lib_env import load_env  # noqa: E402
from shared.gmail_send import send_message  # noqa: E402

DEFAULT_SUBJECT = "[Chat-to-Sheets] Demo draft summary (educational)"
DEFAULT_BODY = """Hello,

This is a **draft** demo email from the Chat-to-Sheets control kit.
- No real institutional data
- Human verifies before any real use
- Generated by control/scripts/send_demo_email.py

If you did not expect this, ignore it (self-test only).

— sheet demo
"""


def main() -> None:
    ap = argparse.ArgumentParser(
        description="Send educational demo email (dry-run default)"
    )
    ap.add_argument(
        "--send",
        action="store_true",
        help="Actually send (default: dry-run only)",
    )
    ap.add_argument(
        "--dry-run",
        action="store_true",
        default=True,
        help=argparse.SUPPRESS,  # default behavior; kept for explicit scripts
    )
    ap.add_argument("--to", default="", help="Recipient (must be allow-listed)")
    ap.add_argument("--from-addr", default="", dest="from_addr", help="Optional From")
    ap.add_argument("--subject", default="", help="Subject line")
    ap.add_argument("--body", default="", help="Plain body (or use --body-file)")
    ap.add_argument("--body-file", default="", help="Read body from file")
    ap.add_argument(
        "--auth",
        choices=("auto", "user", "sa"),
        default="auto",
        help="Auth mode (default auto=user token via gcloud)",
    )
    ap.add_argument("--json", action="store_true", help="Machine-readable result")
    args = ap.parse_args()

    env = load_env()
    # merge process env after load
    for k, v in os.environ.items():
        env.setdefault(k, v)

    to_addr = (args.to or env.get("GMAIL_TO") or env.get("DEMO_OWNER_EMAIL") or "").strip()
    if not to_addr:
        print(
            "ERROR: set GMAIL_TO or DEMO_OWNER_EMAIL in .env, or pass --to\n"
            "See setup/docs/07_gmail_api.md and .env.example",
            file=sys.stderr,
        )
        sys.exit(2)

    subject = args.subject or env.get("GMAIL_SUBJECT") or DEFAULT_SUBJECT
    if args.body_file:
        body = Path(args.body_file).read_text(encoding="utf-8")
    else:
        body = args.body or env.get("GMAIL_BODY") or DEFAULT_BODY

    from_addr = (args.from_addr or env.get("GMAIL_FROM") or "").strip() or None
    do_send = bool(args.send)

    try:
        result = send_message(
            to_addr=to_addr,
            subject=subject,
            body=body,
            from_addr=from_addr,
            send=do_send,
            auth=args.auth,
            env=env,
        )
    except ValueError as e:
        print("ERROR (validation):", e, file=sys.stderr)
        sys.exit(2)
    except RuntimeError as e:
        print("ERROR:", e, file=sys.stderr)
        sys.exit(1)

    if args.json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
    else:
        print("Chat-to-Sheets · demo email")
        print("-" * 50)
        for k in (
            "mode",
            "status",
            "to",
            "from",
            "subject",
            "body_chars",
            "auth",
            "message_id",
            "hint",
        ):
            if k in result and result[k] is not None:
                print(f"{k}: {result[k]}")
        if result.get("body_preview") and not do_send:
            print("body_preview:")
            print(result["body_preview"])
        print("-" * 50)
        if not do_send:
            print("Dry-run only. To send: add --send (whitelist enforced).")


if __name__ == "__main__":
    main()
