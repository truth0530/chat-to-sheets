#!/usr/bin/env python3
"""Create blank demo spreadsheet (user token) and share service account as editor.

Requires:
  - credentials/google-service-account.json
  - gcloud auth login --enable-gdrive-access
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

from google.oauth2 import service_account
from google.oauth2.credentials import Credentials as UserCredentials
from googleapiclient.discovery import build
from googleapiclient.errors import HttpError

ROOT = Path(__file__).resolve().parents[1]
CRED = ROOT / "credentials" / "google-service-account.json"
ENV_PATH = ROOT / ".env"

TITLE = "Chat-to-Sheets Kit — Demo Board (blank)"
DEFAULT_TAB = "DemoBoard"
NOTICE = (
    "Demo board — AI/scripts fill this sheet from chat instructions. "
    "No real personal or institutional identifiers. Draft only; humans verify."
)


def user_token() -> str:
    try:
        return subprocess.check_output(
            ["gcloud", "auth", "print-access-token"], text=True
        ).strip()
    except Exception as e:
        print(
            "ERROR: gcloud access token failed.\n"
            "Run: gcloud auth login --enable-gdrive-access\n"
            "See docs/02_gcloud_cli_auth.md\n",
            e,
            file=sys.stderr,
        )
        sys.exit(1)


def main() -> None:
    if not CRED.is_file():
        print(
            "ERROR: missing",
            CRED,
            "\nCreate a service account key JSON and place it there.\n"
            "See docs/03_service_account_and_sheet.md",
            file=sys.stderr,
        )
        sys.exit(1)

    sa_info = json.loads(CRED.read_text(encoding="utf-8"))
    sa_email = sa_info["client_email"]
    project = sa_info.get("project_id", "")
    print("SA:", sa_email)
    print("project:", project)

    user = UserCredentials(token=user_token())
    sheets_u = build("sheets", "v4", credentials=user, cache_discovery=False)
    drive_u = build("drive", "v3", credentials=user, cache_discovery=False)

    tab = DEFAULT_TAB
    try:
        created = sheets_u.spreadsheets().create(
            body={
                "properties": {"title": TITLE},
                "sheets": [
                    {
                        "properties": {
                            "title": tab,
                            "gridProperties": {"rowCount": 100, "columnCount": 20},
                        }
                    }
                ],
            }
        ).execute()
    except HttpError as e:
        print("ERROR creating spreadsheet:", e, file=sys.stderr)
        print("If scopes insufficient → docs/02_gcloud_cli_auth.md", file=sys.stderr)
        sys.exit(1)

    sid = created["spreadsheetId"]
    url = f"https://docs.google.com/spreadsheets/d/{sid}/edit"
    print("created:", sid)
    print("url:", url)

    sheets_u.spreadsheets().values().update(
        spreadsheetId=sid,
        range=f"'{tab}'!A1",
        valueInputOption="USER_ENTERED",
        body={"values": [[NOTICE]]},
    ).execute()

    drive_u.permissions().create(
        fileId=sid,
        body={"type": "user", "role": "writer", "emailAddress": sa_email},
        sendNotificationEmail=False,
        fields="id",
    ).execute()
    print("shared writer →", sa_email)

    try:
        drive_u.permissions().create(
            fileId=sid,
            body={"type": "anyone", "role": "reader"},
            fields="id",
        ).execute()
        print("anyone with link: reader")
    except HttpError as e:
        print("WARN anyone share:", e)

    # owner email best-effort
    owner = ""
    try:
        owner = subprocess.check_output(
            ["gcloud", "config", "get-value", "account"], text=True
        ).strip()
    except Exception:
        pass

    ENV_PATH.write_text(
        f"""# Generated by scripts/bootstrap.py — do not commit
GOOGLE_CLOUD_PROJECT={project}
GOOGLE_APPLICATION_CREDENTIALS={CRED.resolve()}
GOOGLE_SERVICE_ACCOUNT_EMAIL={sa_email}
SPREADSHEET_ID={sid}
SPREADSHEET_URL={url}
SPREADSHEET_TAB={tab}
DEMO_OWNER_EMAIL={owner}
""",
        encoding="utf-8",
    )
    print("wrote", ENV_PATH)

    sa = service_account.Credentials.from_service_account_file(
        str(CRED), scopes=["https://www.googleapis.com/auth/spreadsheets"]
    )
    sheets_sa = build("sheets", "v4", credentials=sa, cache_discovery=False)
    sheets_sa.spreadsheets().values().update(
        spreadsheetId=sid,
        range=f"'{tab}'!A3",
        valueInputOption="USER_ENTERED",
        body={"values": [["[bootstrap] service account write OK — run clear_board.py before demo"]]},
    ).execute()
    print("SA write OK")
    print("Next: python scripts/smoke_test.py && python scripts/clear_board.py")


if __name__ == "__main__":
    main()
